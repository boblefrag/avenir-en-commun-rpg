def sheet():
    """Planche 128x128 en hex (1 caractere par pixel)."""
    s = [["0"] * 128 for _ in range(128)]

    def put(n, rows, size):
        assert len(rows) == size, f"sprite {n} : {len(rows)} lignes"
        sx, sy = n % 16 * 8, n // 16 * 8
        for j, row in enumerate(rows):
            assert len(row) == size, f"sprite {n} ligne {j} : {len(row)} colonnes"
            for i, c in enumerate(row):
                s[sy + j][sx + i] = "0" if c == "." else c

    for n, rows in TILES.items():
        put(n, rows, 8)
    for n, rows in MONSTERS.items():
        put(n, rows, 16)
    for n, half in BOSSES.items():
        put(n, [h + h[::-1] for h in half], 32)
    return ["".join(r) for r in s]
